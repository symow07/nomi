-- ---------------------------------------------------------------------------
-- 0162 — EACH WORKSPACE NUMBERS ITS OWN ORDERS (the owner, 2026-10-15:
-- "Per-workspace numbering, no shared counter, no YW.")
--
-- Before: `generate_order_reference()` (the baseline schema) wrote
-- 'YW-' || YYYY-MM || '-' || nextval('order_seq'): one counter for the whole
-- installation, the old system's letters on every workspace's orders, gaps in
-- each workspace's numbers, and a number that told a buyer roughly how many
-- orders every workspace together had made.
--
-- Now: a workspace counts its own orders, per year in its own time zone —
-- 2026-0001, 2026-0002 … 2027-0001. The count is one row per workspace and
-- year, raised in the order's own transaction (`src/db/repos.ts`), so an order
-- that rolls back takes its number with it (a sequence would leave a gap), and
-- two orders at once in one workspace wait for each other on that row.
--
-- A reference already issued is never rewritten: a buyer may hold the
-- document. Production had no orders when this was written.
-- ---------------------------------------------------------------------------

create table if not exists order_numbers (
  business_id  uuid not null references businesses(id) on delete cascade,
  year         integer not null check (year between 2000 and 2999),
  last_number  integer not null check (last_number >= 0),
  updated_at   timestamptz not null default now(),
  primary key (business_id, year)
);

-- A reference already in the new shape counts, so the next number cannot
-- repeat it. (None exist: nothing wrote this shape before this migration.)
insert into order_numbers (business_id, year, last_number)
  select business_id,
         substring(order_reference from '^([0-9]{4})-[0-9]+$')::integer,
         max(substring(order_reference from '^[0-9]{4}-([0-9]+)$')::integer)
    from orders
   where order_reference ~ '^[0-9]{4}-[0-9]+$'
   group by 1, 2
  on conflict (business_id, year) do nothing;

alter table order_numbers enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'order_numbers' and policyname = 'order_numbers_tenant') then
    create policy order_numbers_tenant on order_numbers
      for all to nomi_app
      using (business_id = current_business_id())
      with check (business_id = current_business_id());
  end if;
end $$;

grant select, insert, update on order_numbers to nomi_app;
revoke delete, truncate on order_numbers from nomi_app;

-- A reference is unique within its workspace, no longer across all of them:
-- two workspaces each have a 2026-0001.
alter table orders drop constraint if exists orders_order_reference_key;
create unique index if not exists orders_business_reference
  on orders (business_id, order_reference);

-- The shared counter stays in the database (its last value is history) but
-- nothing can call it: the app stopped using it in this release.
revoke execute on function generate_order_reference() from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'nomi_app') then
    revoke execute on function generate_order_reference() from nomi_app;
    revoke usage, select, update on sequence order_seq from nomi_app;
  end if;
end $$;

