export const messages: Record<Locale, Record<MessageKey, string>> = { en: EN, zh: ZH, ar: AR };

/** Employee identity — a product constant per locale (not env/DB-configurable). */
export const EMPLOYEE_NAME: Record<Locale, string> = { en: 'Lily', zh: '小雅', ar: 'ياسمين' };

/** Translate. Falls back to English, then the raw key. `{param}` interpolation. */
export function t(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const table = messages[locale] ?? messages[DEFAULT_LOCALE];
  let s = table[key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  // She has a name. Any string may say {name} without every call site having to
  // pass it — an owner talks about Lily / 小雅 / ياسمين, never "your employee".
  if (s.includes('{name}')) s = s.split('{name}').join(EMPLOYEE_NAME[locale] ?? EMPLOYEE_NAME[DEFAULT_LOCALE]);
  return s;
}

/** Owner-facing name for a country code, localized; the raw code if unknown. */
export function countryName(locale: Locale, code: string | null): string | null {
  if (!code) return null;
  const key = `country.${code}` as MessageKey;
  return key in messages[DEFAULT_LOCALE] ? t(locale, key) : null;
}

/** Localized order-status label; the raw code if unknown. */
export function orderStatusName(locale: Locale, status: string): string {
  const key = `order.status.${status}` as MessageKey;
  return key in messages[DEFAULT_LOCALE] ? t(locale, key) : status;
}

/** Localized capability name; the raw code if unknown. */
/** A claim the owner authorised, in their words. Unknown keys fall back to the key. */
export function claimName(locale: Locale, key: string): string {
  const k = `claim.${key}` as MessageKey;
  return k in messages[DEFAULT_LOCALE] ? t(locale, k) : key;
}

export function capabilityName(locale: Locale, code: string): string {
  const key = `capability.${code}` as MessageKey;
  return key in messages[DEFAULT_LOCALE] ? t(locale, key) : code;
}
